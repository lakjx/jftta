from __future__ import annotations
import re
from typing import Any
from src.common import repeat_4gram_rate

def adjust_candidate_score(cfg: dict[str, Any], tokenizer: Any, record: dict[str, Any], score: float) -> float:
    search_cfg = cfg.get("search", {})
    text = str(record.get("text", ""))
    repeat_threshold = float(search_cfg.get("mpc_quality_repeat_threshold", 0.16))
    repeat_weight = float(search_cfg.get("mpc_quality_repeat_penalty", 0.8))
    hit_max_penalty = float(search_cfg.get("mpc_quality_hit_max_penalty", 0.08))
    trimmed_penalty = float(search_cfg.get("mpc_quality_trimmed_penalty", 0.04))
    long_token_threshold = int(search_cfg.get("mpc_quality_long_token_threshold", int(cfg["generation"]["max_new_tokens"]) - 16))
    long_token_penalty = float(search_cfg.get("mpc_quality_long_token_penalty", 0.04))
    meta_penalty = float(search_cfg.get("mpc_quality_meta_penalty", 0.15))
    adjusted = float(score)
    repeat = repeat_4gram_rate(text)
    if repeat > repeat_threshold:
        adjusted -= repeat_weight * (repeat - repeat_threshold)
    raw = record.get("raw") or {}
    if raw.get("hit_max_new_tokens"):
        adjusted -= hit_max_penalty
    if raw.get("sentence_trimmed"):
        adjusted -= trimmed_penalty
    if token_count(tokenizer, text) >= long_token_threshold:
        adjusted -= long_token_penalty
    if contains_low_value_phrase(text):
        adjusted -= meta_penalty
    return adjusted


def contains_low_value_phrase(text: str) -> bool:
    lowered = normalize_for_dedup(text)
    low_value_phrases = (
        "if you have any further questions",
        "i hope this helps",
        "thank you for your understanding",
        "let me know if you need",
        "final answer",
        "candidate answer",
        "sample candidate",
        "sample answer",
        "please note",
        "gpt-3",
        "language model",
        "generated by",
        "should not be used as a template",
        "this is a template",
        "this answer is tailored",
        "validated useful",
        "useful content to preserve",
        "potentially useful reference content",
        "selected draft",
        "reward",
        "validation score",
    )
    return any(phrase in lowered for phrase in low_value_phrases)


def normalize_for_dedup(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().lower())


def normalize_mpc_segment(text: str, tokenizer: Any, min_tokens: int, allow_short: bool = False) -> tuple[str, bool]:
    stripped = text.strip()
    if not stripped:
        return "", True
    if allow_short:
        return stripped, False
    cuts = boundary_cuts(stripped)
    for cut in sorted(cuts, reverse=True):
        candidate = stripped[:cut].strip()
        if candidate and token_count(tokenizer, candidate) >= min_tokens:
            return candidate, False
    return stripped, True


def boundary_cuts(text: str) -> list[int]:
    cuts: set[int] = set()
    for match in re.finditer(r"[.!?][\"')\]]?(?=\s|$)", text):
        cuts.add(match.end())
    for match in re.finditer(r"\n+", text):
        cuts.add(match.end())
    if text.count("```") >= 2:
        cuts.add(text.rfind("```") + 3)
    return sorted(cut for cut in cuts if cut > 0)


def append_segment(prefix: str, segment: str) -> str:
    left = prefix.strip()
    right = segment.strip()
    if not left:
        return right
    if right.startswith((".", ",", ";", ":", "!", "?", ")", "]")):
        return left + right
    if left.endswith("\n") or right.startswith("\n"):
        return left + right
    return left + " " + right


def token_count(tokenizer: Any, text: str) -> int:
    if not text:
        return 0
    return len(tokenizer(text, add_special_tokens=False)["input_ids"])
